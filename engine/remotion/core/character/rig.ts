/** A species preset, with any fields overridden (colours are merged). */
export function rigFor(species: Species, overrides: Partial<Omit<Rig, "colours">> & { colours?: Partial<Rig["colours"]> } = {}): Rig {
  const preset = PRESETS[species];
  if (!preset) throw new Error(`Unknown species "${String(species)}"; choose one of ${SPECIES.join(", ")}`);
  return { ...preset, ...overrides, colours: { ...preset.colours, ...overrides.colours }, accessories: overrides.accessories ?? preset.accessories };
}
